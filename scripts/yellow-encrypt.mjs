#!/usr/bin/env node
// Encrypts Yellow's private content for the static host.
//
//   npm run yellow:encrypt            yellow/private/{panels.html,data.mjs} -> yellow/assets/data/yellow.enc,
//                                     then copies the shell into the five entry folders
//   npm run yellow:decrypt            yellow.enc -> yellow/private/ (recovery on a fresh checkout; add --force to overwrite)
//
// The password comes from YELLOW_PASSWORD (environment or .env, both ignored by git) or an
// interactive prompt. yellow/private/ is ignored by git; only the ciphertext is committed.
import { existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { DEFAULT_ITERATIONS, decryptPayload, encryptPayload, normalizePassword } from "./yellow-crypto.mjs";
import { ENTRY_FOLDERS, ROOT, syncEntryPoints } from "./yellow-sync.mjs";

const PRIVATE_DIR = join(ROOT, "yellow", "private");
const PANELS_FILE = join(PRIVATE_DIR, "panels.html");
const DATA_FILE = join(PRIVATE_DIR, "data.mjs");
const OUTPUT_FILE = join(ROOT, "yellow", "assets", "data", "yellow.enc");
const PAYLOAD_VERSION = 1;

const args = new Set(process.argv.slice(2));
const iterationsArg = process.argv.find((arg) => arg.startsWith("--iterations="));
const iterations = iterationsArg ? Number(iterationsArg.split("=")[1]) : DEFAULT_ITERATIONS;

loadEnvironment(join(ROOT, ".env"));

try {
  if (args.has("--decrypt")) {
    await decrypt();
  } else {
    await encrypt();
  }
} catch (error) {
  console.error(`\n${error.message}`);
  process.exit(1);
}

async function encrypt() {
  if (!existsSync(PANELS_FILE) || !existsSync(DATA_FILE)) {
    throw new Error(`Missing ${relative(PANELS_FILE)} or ${relative(DATA_FILE)}. On a fresh checkout run \`npm run yellow:decrypt\` first.`);
  }

  const panels = readFileSync(PANELS_FILE, "utf8");
  const dataModule = await import(`${pathToFileURL(DATA_FILE).href}?t=${statSync(DATA_FILE).mtimeMs}`);
  const data = Object.fromEntries(Object.entries(dataModule).filter(([key]) => key !== "default"));
  const payload = { version: PAYLOAD_VERSION, panels, data };
  const password = await getPassword("Yellow password: ");

  const started = Date.now();
  const envelope = await encryptPayload(payload, password, { iterations });
  mkdirSync(join(OUTPUT_FILE, ".."), { recursive: true });
  writeFileSync(OUTPUT_FILE, `${JSON.stringify(envelope, null, 2)}\n`);

  const plainBytes = Buffer.byteLength(JSON.stringify(payload));
  const encBytes = statSync(OUTPUT_FILE).size;
  console.log(`Encrypted ${Object.keys(data).length} data exports + panels (${kb(plainBytes)}) -> ${relative(OUTPUT_FILE)} (${kb(encBytes)}), PBKDF2 x${iterations.toLocaleString("en-US")} in ${Date.now() - started} ms.`);

  const written = syncEntryPoints(ROOT);
  console.log(`Copied yellow/index.html to ${written.length} entry points: ${ENTRY_FOLDERS.join(", ")}.`);
}

async function decrypt() {
  if (!existsSync(OUTPUT_FILE)) throw new Error(`${relative(OUTPUT_FILE)} does not exist.`);
  if ((existsSync(PANELS_FILE) || existsSync(DATA_FILE)) && !args.has("--force")) {
    throw new Error(`${relative(PRIVATE_DIR)} already has files. Pass --force to overwrite them from the ciphertext.`);
  }

  const envelope = JSON.parse(readFileSync(OUTPUT_FILE, "utf8"));
  const password = await getPassword("Yellow password: ");
  const payload = await decryptPayload(envelope, password);

  if (payload.version !== PAYLOAD_VERSION) throw new Error(`Unexpected payload version ${payload.version}.`);

  mkdirSync(PRIVATE_DIR, { recursive: true });
  writeFileSync(PANELS_FILE, payload.panels);
  writeFileSync(DATA_FILE, renderDataModule(payload.data));
  console.log(`Wrote ${relative(PANELS_FILE)} and ${relative(DATA_FILE)} (${Object.keys(payload.data).length} exports).`);
}

function renderDataModule(data) {
  const header = [
    "// Private Yellow content: health programme, recipes, food plans, and letter drafts.",
    "// This file is ignored by git. `npm run yellow:encrypt` bundles it with panels.html",
    "// into yellow/assets/data/yellow.enc; the browser decrypts it after the password unlock.",
    "// Keep every value JSON-serialisable (plain objects, arrays, strings, numbers).",
    "// (Regenerated by `npm run yellow:decrypt`; formatting and comments are not preserved.)",
    "",
  ].join("\n");
  const body = Object.entries(data).map(([key, value]) => `export const ${key} = ${JSON.stringify(value, null, 2)};`).join("\n");
  return `${header}\n${body}\n`;
}

async function getPassword(label) {
  const fromEnv = process.env.YELLOW_PASSWORD;
  if (normalizePassword(fromEnv)) return fromEnv;
  if (!process.stdin.isTTY) throw new Error("Set YELLOW_PASSWORD (environment or .env) when running without a terminal.");
  const typed = await promptHidden(label);
  if (!normalizePassword(typed)) throw new Error("No password entered.");
  return typed;
}

function promptHidden(label) {
  return new Promise((resolvePrompt) => {
    const { stdin, stdout } = process;
    let value = "";
    stdout.write(label);
    stdin.setRawMode(true);
    stdin.resume();
    stdin.setEncoding("utf8");
    const onData = (chunk) => {
      for (const char of chunk) {
        if (char === "\r" || char === "\n") {
          stdin.setRawMode(false);
          stdin.pause();
          stdin.off("data", onData);
          stdout.write("\n");
          resolvePrompt(value);
          return;
        }
        if (char === "\u0003") {
          stdout.write("\n");
          process.exit(130);
        }
        if (char === "\u007f" || char === "\b") {
          value = value.slice(0, -1);
          continue;
        }
        value += char;
      }
    };
    stdin.on("data", onData);
  });
}

function loadEnvironment(filePath) {
  if (!existsSync(filePath)) return;
  for (const line of readFileSync(filePath, "utf8").split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const separator = trimmed.indexOf("=");
    if (separator < 1) continue;
    const key = trimmed.slice(0, separator).trim();
    const value = trimmed.slice(separator + 1).trim().replace(/^(['"])(.*)\1$/, "$2");
    if (!(key in process.env)) process.env[key] = value;
  }
}

function relative(file) {
  return resolve(file).slice(ROOT.length + 1);
}

function kb(bytes) {
  return `${(bytes / 1024).toFixed(1)} KB`;
}
